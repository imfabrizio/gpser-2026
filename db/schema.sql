  ruolo_gara    text,                            -- ruolo in gara chiesto in registrazione (partecipante_leader, allenatore...)
  squadra_id    uuid,                            -- FK aggiunta dopo la tabella squadra
  cf_cifrato    text,                            -- codice fiscale cifrato
